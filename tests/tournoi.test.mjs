import assert from 'node:assert/strict';
import { test } from 'node:test';
import { spawn } from 'node:child_process';
import { copyFile, mkdtemp, mkdir, rm, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:net';

test('tournoi : authentification, validation, classement, finales et conflits', async () => {
  const root = await mkdtemp(join(tmpdir(), 'bears-tournament-'));
  const web = join(root, 'web');
  await mkdir(join(web,'config'), { recursive:true });
  await mkdir(join(root,'storage'));
  for (const file of ['tournoi-api.php','tournoi-public.php','tournoi-domain.php','tirage-equipes.php','private-backup.php','bears-storage.php']) await copyFile(file,join(web,file));
  await writeFile(join(web,'config/family-day-config.php'), "<?php return ['storage_dir'=>__DIR__.'/../../storage'];");
  await writeFile(join(web,'login.php'), "<?php session_start(); $_SESSION['family_dashboard_until']=time()+3600; $_SESSION['family_dashboard_csrf']='test';");
  const socket=createServer(); await new Promise(r=>socket.listen(0,'127.0.0.1',r)); const port=socket.address().port; await new Promise(r=>socket.close(r));
  const origin=`http://127.0.0.1:${port}`;
  const server=spawn('php',['-S',`127.0.0.1:${port}`,'-t',web],{stdio:'ignore'});
  try {
    let login;
    for(let i=0;i<60;i++) { try { login=await fetch(`${origin}/login.php`); break; } catch { await new Promise(r=>setTimeout(r,50)); } }
    assert.ok(login,'PHP démarre');
    const cookie=login.headers.get('set-cookie').split(';')[0];
    assert.equal((await fetch(`${origin}/tournoi-api.php`)).status,401);
    const publicBefore=await (await fetch(`${origin}/tournoi-public.php`)).json();
    assert.equal(publicBefore.ready,false);
    assert.deepEqual(publicBefore.teams,[]);
    assert.equal((await fetch(`${origin}/tournoi-public.php`,{method:'POST'})).status,405);
    const get=async()=> (await fetch(`${origin}/tournoi-api.php`,{headers:{Cookie:cookie}})).json();
    let data=await get();
    const post=async(payload,expected=200)=>{
      const response=await fetch(`${origin}/tournoi-api.php`,{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json'},body:JSON.stringify({csrf:data.csrf,version:data.version,sourceVersion:data.source.version,...payload})});
      const result=await response.json(); assert.equal(response.status,expected,JSON.stringify(result));
      if(expected===200) data=result;
      return result;
    };
    assert.equal(data.preview.length,0); assert.equal(data.state,null);
    await post({action:'validate',acceptExceptions:true},422);
    let drawVersion='';
    const draw={roster:Array.from({length:19},(_,i)=>({id:`sur-place-${i+1}`,name:`Joueur été ${i+1}`,present:true,woman:i%3===0,minor:i%3===1,bears:i%3!==2})),teams:Array.from({length:6},(_,t)=>Array.from({length:3},(_,i)=>`sur-place-${t*3+i+1}`)),waiting:['sur-place-19'],links:[],seed:22,teamCount:6,revision:1};
    // One person meets all three roles; the other two meet none.
    Object.assign(draw.roster[0],{woman:true,minor:true,bears:false});
    Object.assign(draw.roster[1],{minor:false}); Object.assign(draw.roster[2],{bears:true});
    const saveDraw=async()=>{
      const response=await fetch(`${origin}/tirage-equipes.php`,{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json'},body:JSON.stringify({csrf:'test',version:drawVersion,state:draw})});
      const body=await response.json(); assert.equal(response.status,200,JSON.stringify(body)); drawVersion=body.version;
    };
    await saveDraw(); data=await get();
    assert.equal(data.preview.length,6);
    assert.deepEqual(data.preview.map(t=>t.players.map(p=>p.id)),draw.teams,'Le tournoi reprend exactement le tirage sauvegardé');
    assert.deepEqual(data.source.waiting,['Joueur été 19']);
    assert.deepEqual(data.preview[0].exceptions,['Moins de 18 ans : aucun représentant distinct disponible','Hors Bears : aucun représentant distinct disponible']);
    assert.equal(new Set(data.preview.flatMap(t=>t.players.map(p=>p.id))).size,data.preview.reduce((n,t)=>n+t.players.length,0));
    assert.ok(data.preview.some(t=>t.exceptions.length));
    assert.equal(new Set(data.matches.map(p=>[...p].sort().join('-'))).size,15);
    for(let t=0;t<6;t++) assert.equal(data.matches.filter(p=>p.includes(t)).length,5);
    for(let i=1;i<15;i++) assert.ok(data.matches[i].every(t=>!data.matches[i-1].includes(t)),'Pas de matchs consécutifs sur un terrain');
    await post({action:'validate',acceptExceptions:true,csrf:'bad'},403);
    await post({action:'validate'},422);
    const staleSource=data.source.version;
    [draw.teams[0][1],draw.teams[1][1]]=[draw.teams[1][1],draw.teams[0][1]];
    await saveDraw();
    await post({action:'validate',acceptExceptions:true,sourceVersion:staleSource},409);
    data=await get();
    await post({action:'validate',acceptExceptions:true});
    assert.equal(data.state.scores.length,18);
    const publicReady=await (await fetch(`${origin}/tournoi-public.php`)).json();
    assert.equal(publicReady.ready,true);
    assert.equal(publicReady.teams.length,6);
    assert.deepEqual(Object.keys(publicReady.teams[0]),['name'],'Aucun joueur ou capitaine dans le flux public');
    assert.equal(publicReady.scores.length,18);
    assert.deepEqual(data.state.settings,{start:'09:15',minutes:20,transition:10,fields:3,break:15});
    await post({action:'validate',acceptExceptions:true},409);
    const names=['Les Oursons','Les Éclairs','La meute','Les Vikings','Les Loups','Les Dragons'];
    await post({action:'names',names:['Unique']},422);
    await post({action:'names',names:['',...names.slice(1)]},422);
    await post({action:'names',names:['A'.repeat(33),...names.slice(1)]},422);
    await post({action:'names',names:['LES ÉCLAIRS',...names.slice(1)]},422);
    await post({action:'names',names});
    assert.deepEqual(data.state.teams.map(t=>t.name),names);
    assert.equal(data.sourceChanged,false,'Renommer ne change pas les compositions');
    const captains=draw.teams.map(t=>t[0]); captains[0]=draw.teams[0][2];
    await post({action:'names',names,captains:[draw.teams[1][0],...captains.slice(1)]},422);
    await post({action:'names',names,captains:['inconnu',...captains.slice(1)]},422);
    await post({action:'names',names,captains});
    assert.deepEqual(data.state.teams.map(t=>t.captainId),captains);
    assert.equal(data.sourceChanged,false,'Les capitaines ne changent pas la composition');
    const frozen=structuredClone(data.state.teams);
    [draw.teams[0][2],draw.teams[1][2]]=[draw.teams[1][2],draw.teams[0][2]];
    await saveDraw(); data=await get();
    assert.equal(data.sourceChanged,true);
    assert.deepEqual(data.state.teams,frozen,'Pas de remplacement silencieux après validation');
    await post({action:'replace-teams'},422);
    await post({action:'replace-teams',acceptExceptions:true});
    assert.deepEqual(data.state.teams.map(t=>t.players.map(p=>p.id)),draw.teams);
    assert.deepEqual(data.state.teams.map(t=>t.name),names,'Noms conservés lors de la reprise du tirage');
    assert.equal(data.state.teams[0].captainId,null,'Capitaine retiré si son joueur change d’équipe');
    assert.equal(data.state.teams[1].captainId,captains[1],'Capitaine conservé si le joueur reste dans son équipe');
    assert.equal(data.sourceChanged,false);
    const validatedVersion=data.version;
    await post({action:'score',match:15,score:[6,0]},422);
    await post({action:'score',match:0,score:[-1,0]},422);
    await post({action:'score',match:0,score:[1.5,0]},422);
    await post({action:'score',match:0,score:[0,0]});
    await post({action:'replace-teams',acceptExceptions:true},409);
    assert.equal(data.standings.find(r=>r.id===0).points,1);
    const scoresBeforeNames=structuredClone(data.state.scores);
    await post({action:'names',names:['Les Ours',...names.slice(1)]});
    assert.deepEqual(data.state.scores,scoresBeforeNames,'Renommer après un match préserve les résultats');
    const newCaptains=draw.teams.map(t=>t[0]);
    await post({action:'names',names,captains:newCaptains});
    assert.deepEqual(data.state.scores,scoresBeforeNames,'Changer les capitaines ne modifie aucun score');
    await post({action:'score',match:1,score:[6,0],version:validatedVersion},409);
    for(let i=1;i<15;i++) await post({action:'score',match:i,score:[0,0]});
    assert.equal(data.finals,null,'Égalités parfaites bloquent les finales');
    await post({action:'ties',order:[0,0,1,2,3,4]},422);
    await post({action:'ties',order:[5,4,3,2,1,0]});
    assert.deepEqual(data.finals,[[1,0],[3,2],[5,4]]);
    await post({action:'score',match:15,score:[6,6]},422);
    await post({action:'score',match:15,score:[6,0]});
    const publicScore=await (await fetch(`${origin}/tournoi-public.php`)).json();
    assert.deepEqual(publicScore.scores[15],[6,0]);
    assert.deepEqual(publicScore.finals,data.finals);
    await post({action:'score',match:0,score:[6,0]},409);
    await post({action:'ties',order:[0,1,2,3,4,5]},409);
    await post({action:'score',match:15,score:null});
    await post({action:'score',match:0,score:[6,0]});
    assert.equal(data.state.tieOrder,undefined);
    assert.equal(data.standings.find(r=>r.id===0).points,7);
    await post({action:'settings',settings:{start:'09:00',minutes:10,transition:2,fields:4,break:10}},422);
    await post({action:'settings',settings:{start:'09:00',minutes:10,transition:2,fields:2,break:10}});
    await post({action:'settings',settings:{start:'09:15',minutes:20,transition:10,fields:3,break:15}});
    assert.deepEqual((await get()).state,data.state,'Persistance après rechargement');
    assert.deepEqual(JSON.parse(await readFile(join(root,'storage/family-tournament-2026.json'),'utf8')),data.state);
  } finally { server.kill(); await new Promise(r=>server.once('exit',r)); await rm(root,{recursive:true,force:true}); }
});
